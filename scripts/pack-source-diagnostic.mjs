#!/usr/bin/env node
// Diagnostic-only source pack. Smaller than `pack-source.mjs` so the
// user can ship the relevant slices of code to me without paying for
// generated dist/ artefacts (the full bundle is ~175 MB compressed
// and clutters review). Includes:
//   - src/           all TypeScript source (api, watcher, ingestion, ai, db, …)
//   - scripts/       PowerShell + .py + .mjs helpers (com-extract.ps1 etc.)
//   - migrations/    SQL migrations (.sql)
//   - web/src/       Web UI TSX source
//   - package.json + tsconfig*.json  so the reader can reproduce builds
//   - src/watcher/__tests__/ + scripts/__tests__/   representative test cases
//Skips:
//   - dist/ (build output, regenerated by build:sea-bundle)
//   - node_modules/ (npm ci to restore)
//   - web/dist/ (compiled web artefacts)
//   - all .log/.png/.jpg/tmp artefacts
import { spawn } from "node:child_process";
import path from "node:path";

const ROOT = path.resolve(process.argv[2] ?? "E:\\sag\\export");
const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const OUT = process.argv[3] ?? `E:\\sag\\dist\\sag-diag-${stamp}.zip`;

// We pass each path as a separate positional arg so tar's --exclude
// rules apply only to the rest of the tree. This keeps the pack
// tight even if `dist/` shows up alongside `src/`.
const INCLUDES = [
  "src",
  "scripts",
  "migrations",
  "package.json",
  "tsconfig.json",
  "tsconfig.build.json",
  "tsconfig.build.json",
  "web/src",
  "web/index.html",
  "web/package.json",
  "web/tsconfig.json",
  "web/vite.config.ts",
  "web/postcss.config.js",
  "web/tailwind.config.js"
];

console.log(`packing ${ROOT} -> ${OUT}`);
const args = [
  "-cf", OUT,
  "--exclude=node_modules",
  "--exclude=dist",
  "--exclude=test-model",
  "--exclude=.trae",
  "--exclude=.tmp",
  "--exclude=release-staging",
  "--exclude=.git",
  "--exclude=test-smoke.xlsx",
  "--exclude=test-large.xlsx",
  "--exclude=~*",
  "--exclude=*.log",
  "--exclude=*.png",
  "--exclude=*.jpg",
  "--exclude=*.jpeg",
  "--exclude=*.ico",
  "--exclude=*.zip",
  "-C", ROOT,
  ...INCLUDES
];
const t = spawn("tar", args, { stdio: "inherit" });
t.on("close", (code) => {
  if (code === 0) console.log(`done (tar exit ${code})`);
  else console.log(`tar exit ${code}`);
});